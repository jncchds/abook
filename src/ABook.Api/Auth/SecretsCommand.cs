using ABook.Infrastructure.Data;
using Microsoft.EntityFrameworkCore;

namespace ABook.Api.Auth;

/// <summary>
/// <c>dotnet ABook.Api.dll secrets show</c> — prints the secrets the server generated and stored in the database
/// as ready-to-paste environment variables, so they can be moved into the deployment's configuration.
/// In Docker: <c>docker compose exec abook-api dotnet ABook.Api.dll secrets show</c>.
/// </summary>
public static class SecretsCommand
{
    public static bool Matches(string[] args) => args.Length > 0 && args[0] == "secrets";

    public static async Task<int> RunAsync(string[] args, string connectionString, IConfiguration configuration)
    {
        if (args.Length < 2 || args[1] != "show")
        {
            Console.Error.WriteLine("Usage: dotnet ABook.Api.dll secrets show");
            return 2;
        }

        var options = new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql(connectionString, o => o.UseVector())
            .Options;
        await using var db = new AppDbContext(options);

        var stored = await db.ServerSecrets.AsNoTracking().OrderBy(s => s.Name).ToListAsync();
        if (stored.Count == 0)
        {
            Console.WriteLine("# No generated secrets are stored in the database.");
            return 0;
        }

        Console.WriteLine("# Secrets generated by ABook and stored in its database.");
        Console.WriteLine("# Add these lines to the abook-api service's environment, then recreate the container.");
        foreach (var secret in stored)
        {
            var envName = secret.Name.Replace(":", "__");
            var inUse = string.IsNullOrWhiteSpace(configuration[secret.Name]) ? "" : "   # already set in the environment, which takes precedence";
            Console.WriteLine($"{envName}={secret.Value}{inUse}");
        }
        return 0;
    }
}
